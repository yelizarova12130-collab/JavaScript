// створити функцію, яка створює параграф з текстом та виводить його через document.write.
// Текст задати через аргумент

function paragraph (text) {
    document.write(`<p> ${text} </p>`);
}

paragraph('I wish you a wonderful day,');
paragraph(' May the sun shine bright and warm your way.');
paragraph('May luck stay with you all day through,');
paragraph( 'Without sadness, stress, or feeling blue.');
paragraph( 'And may your heart feel light and bright 🌷');


